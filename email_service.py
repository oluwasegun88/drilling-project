    # ── Public methods ────────────────────────────────────────────────────────

    def send_email(
        self,
        subject:     str,
        html_body:   str,
        attachments: List[Tuple[bytes, str, str]],
    ):
        """
        Send an email with attachments.

        Args:
            subject:     Email subject line.
            html_body:   HTML content of the email body.
            attachments: List of (file_bytes, filename, mime_type) tuples.
        """
        msg            = MIMEMultipart("mixed")
        msg["From"]    = self.config.email
        msg["To"]      = ", ".join(self.config.recipients)
        msg["Subject"] = subject

        msg.attach(MIMEText(html_body, "html"))

        for file_bytes, filename, mime_type in attachments:
            self._attach_file(msg, file_bytes, filename, mime_type)

        try:
            server = self._connect()
            server.sendmail(
                self.config.email,
                self.config.recipients,
                msg.as_string(),
            )
            server.quit()
            logger.info("Email sent | subject='%s' to=%s",
                        subject, self.config.recipients)
            print(f"✅ Email sent: {subject}")

        except Exception as e:
            logger.error("Failed to send email: %s", e)
            print(f"❌ Email failed: {e}")
            raise

    def send_daily_report(
        self,
        csv_bytes:     bytes,
        csv_filename:  str,
        pdf_bytes:     bytes,
        pdf_filename:  str,
        date_str:      str,
        asset:         str = None,
        total_records: int = 0,
    ):
        """Send the daily production report with CSV and PDF attached."""
        subject   = f"Daily Production Report — {date_str} | {asset or 'All Assets'}"
        html_body = self._build_daily_html(date_str, asset, total_records)

        self.send_email(
            subject=subject,
            html_body=html_body,
            attachments=[
                (csv_bytes, csv_filename, "text/csv"),
                (pdf_bytes, pdf_filename, "application/pdf"),
            ],
        )

    def send_monthly_report(
        self,
        csv_bytes:     bytes,
        csv_filename:  str,
        pdf_bytes:     bytes,
        pdf_filename:  str,
        year:          int,
        month:         int,
        asset:         str = None,
        total_records: int = 0,
    ):
        """Send the monthly production report with CSV and PDF attached."""
        month_name = calendar.month_name[month]
        subject    = f"Monthly Production Report — {month_name} {year} | {asset or 'All Assets'}"
        html_body  = self._build_monthly_html(year, month, asset, total_records)

        self.send_email(
            subject=subject,
            html_body=html_body,
            attachments=[
                (csv_bytes, csv_filename, "text/csv"),
                (pdf_bytes, pdf_filename, "application/pdf"),
            ],
        )