import smtplib
import logging
import calendar
from email.mime.multipart import MIMEMultipart
from email.mime.text      import MIMEText
from email.mime.base      import MIMEBase
from email                import encoders
from typing               import List, Tuple

from email_config import EmailConfig

logger = logging.getLogger(__name__)


class EmailService:
    """
    Service class for sending production reports via Gmail SMTP.

    Handles:
        - Connecting and authenticating to Gmail SMTP
        - Building HTML email bodies
        - Attaching CSV and PDF files
        - Sending to one or multiple recipients

    Usage:
        config        = EmailConfig.from_env()
        email_service = EmailService(config)
        email_service.send_daily_report(...)
    """

    def __init__(self, config: EmailConfig):
        self.config = config
        self.config.validate()

    # ── Private helpers ───────────────────────────────────────────────────────

    def _connect(self) -> smtplib.SMTP:
        """Create and return an authenticated Gmail SMTP connection."""
        server = smtplib.SMTP(self.config.smtp_host, self.config.smtp_port)
        server.ehlo()
        server.starttls()
        server.login(self.config.email, self.config.password)
        logger.info("SMTP connected to %s", self.config.smtp_host)
        return server

    def _attach_file(
        self,
        msg:        MIMEMultipart,
        file_bytes: bytes,
        filename:   str,
        mime_type:  str,
    ):
        """Attach a file to the email message."""
        part = MIMEBase("application", "octet-stream")
        part.set_payload(file_bytes)
        encoders.encode_base64(part)
        part.add_header(
            "Content-Disposition",
            f'attachment; filename="{filename}"',
        )
        part.add_header("Content-Type", mime_type)
        msg.attach(part)

